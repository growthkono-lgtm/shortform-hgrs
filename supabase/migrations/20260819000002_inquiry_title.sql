-- 문의 폼에 **직함**을 받는다. (2026-08-19)
--
-- 사장님 지시: *"문의폼에 앞으로는 직급도 받자. 뭐라 부를지 모르겠네."*
--
-- 컬럼 이름을 `title` 로 둔 이유: "직급" 은 사내 등급(대리·과장)이고, 명함에
-- 적히고 우리가 통화에서 부를 말은 **직함**(대표·이사·팀장)이다. 우리가 알고
-- 싶은 건 뒤쪽이다 — 첫 마디를 "대표님" 으로 열지 "팀장님" 으로 열지가 갈린다.
--
-- 선택지를 만들지 않고 **자유 입력**으로 받는다(사장님 지시). 회사마다 직함
-- 체계가 달라서 목록을 만들면 반드시 "기타" 로 몰리고, 그러면 안 물어본 것과
-- 같아진다. 적어 준 그대로 부르는 게 맞다.
--
-- ⚠️ NOT NULL 로 두지 않는다. 이 컬럼이 생기기 전에 접수된 21건이 있고,
-- 앞으로도 안 적고 보내는 사람이 있다. 필수로 만들면 그 사람은 접수를 포기한다.
alter table public.inquiries
  add column if not exists contact_title text;

