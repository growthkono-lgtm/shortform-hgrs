-- 라스트 터치 + 방문 횟수. (2026-08-21)
--
-- 사장님 지시: *"first touch / last touch라고 그로스툴에서는 말하거든. …
-- 내가 원하는 건 블로그 컨텐츠 통해 우리 홈페이지에 유입했던 고객인지가
-- 궁금. 그리고 첫방문인지 재방문유저인지도."*
--
-- 08-19 에 **첫 접점**은 붙였다(`20260819000001`). 없는 건 둘이다.
--
--   1. 라스트 터치 — 신청 직전에 **마지막으로** 우리를 찾은 경로.
--      첫 접점만 있으면 "블로그로 알게 됐다" 는 알아도 "오늘 왜 다시 왔나"
--      는 모른다. 광고를 돌리기 시작하면 이 값이 예산 판단의 근거가 된다.
--
--   2. 방문 횟수 — 첫 방문에 바로 신청했나, 몇 번 오간 끝에 신청했나.
--      둘은 완전히 다른 고객이다. 첫 방문 전환은 니즈가 이미 선 사람이고,
--      재방문 전환은 콘텐츠가 설득한 사람이다. 통화 첫 마디가 달라야 한다.
--
-- 세는 단위는 **외부에서 들어온 횟수**다. 사이트 안에서 페이지를 넘기는 건
-- 방문이 아니다 — 그걸 세면 한 번 와서 다섯 장 본 사람이 5회 방문이 된다.
-- ─────────────────────────────────────────────────────────────
alter table public.inquiries
  -- 신청 직전 마지막 진입 경로. 첫 접점과 같을 수 있다(한 번에 신청한 경우)
  add column if not exists last_path text,
  add column if not exists last_referrer text,
  add column if not exists last_at timestamptz,
  -- 외부에서 들어온 횟수. 1 이면 첫 방문에 바로 신청한 것이다
  add column if not exists visit_count integer;

comment on column public.inquiries.last_path is
  '신청 직전 마지막으로 착지한 경로 (2026-08-21부터 기록)';
comment on column public.inquiries.last_referrer is
  '마지막 진입의 리퍼러 원문. 첫 접점과 다르면 다른 경로로 다시 온 것이다';
comment on column public.inquiries.visit_count is
  '외부에서 들어온 횟수. 1=첫 방문 전환 / 2 이상=재방문 전환. 내부 페이지 이동은 세지 않는다';
