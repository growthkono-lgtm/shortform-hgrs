-- ─────────────────────────────────────────────────────────────
-- 2026-08-10 플랜 명칭 통일 — 스타터 / 그로스 / 스케일
--
-- 숏폼 단독을 편수("5편")로 부르고 시딩 포함만 티어명("스타터")으로 부르던 걸
-- 한 이름으로 묶는다. 같은 규모의 두 구성이 요금표 한 박스 안에 위아래로 놓이기 때문에
-- 이름이 갈라져 있으면 무엇과 무엇을 비교하는 건지 읽히지 않는다.
--   숏폼 단독      → 스타터 / 그로스 / 스케일
--   시딩 포함 묶음 → 스타터 패키지 / 그로스 패키지 / 스케일 패키지
--
-- tier 키('5','10','20','starter'…)는 그대로 둔다 — URL 슬러그와 기존 주문이 물려 있다.
-- 편수는 composition 컬럼이 계속 들고 있다.
-- ─────────────────────────────────────────────────────────────

update public.plans set label = v.label
from (values
  ('full',        'starter', '스타터 패키지'),
  ('full',        'growth',  '그로스 패키지'),
  ('full',        'scale',   '스케일 패키지'),
  ('shorts_only', '5',       '스타터'),
  ('shorts_only', '10',      '그로스'),
  ('shorts_only', '20',      '스케일')
) as v(code, tier, label)
where public.plans.code = v.code and public.plans.tier = v.tier;
