-- 시의성 수집 예약 — 주 1회. (2026-08-18)
--
-- 사장님 지시: *"편성표도 주 단위로 한번씩 업데이트해야겠네. 열 별로 숫자나
-- 내용 빠지는 거 없이 체크하면서. 그래야 진짜 시즌성이겠지."*
--
-- 일요일 07:20 KST(= 22:20 UTC 토) 에 그 주 소식을 모은다. 왜 이 시각인가 —
-- 첫 시의성 슬롯이 **월요일**이고, 생성 창이 월요일 09:00 KST 부터다.
-- 그 전에 후보가 표에 들어와 있어야 월요일 편이 시의성으로 나간다.
--
-- 실패해도 편성은 안 멈춘다. 후보가 없으면 평소 니치 풀로 돈다.
select cron.schedule(
  'blog-trends',
  '20 22 * * 6',
  'select public.blog_cron_hit(''trends'')'
);
