/**
 * 검색어 하나가 **누가 치는 말인지** 판정한다.
 *
 * 순서가 중요하다 — 위에서부터 먼저 걸리는 것을 쓴다. `creator` 를
 * `fandom` 보다 먼저 두는 이유: "인플루언서 마케팅" 은 브랜드도 치고
 * 인플루언서도 치는데, 인플루언서 축 신호가 더 구체적이라 그쪽이 맞을
 * 확률이 높다. 어느 쪽도 안 걸리면 **`champion`** 이 기본값이다 —
 * 우리 매출의 본체가 그쪽이고, 애매하면 본체로 보내는 게 맞다.
 */
export function leadTargetOf(term: string | null | undefined): LeadTarget {
  const t = (term ?? "").replace(/\s+/g, "");
  /**
   * ⚠️ **champion 을 맨 뒤에 둔다.** (2026-08-19 수정)
   *
   * 첫 판은 champion 을 fandom 보다 먼저 봤다. champion 신호에 `광고`·`콘텐츠`
   * 계열이 넓게 들어 있어서 **브랜딩·콘텐츠마케팅·채널운영이 통째로 champion
   * 으로 흡수됐다** — 실측에서 fandom 이 264개 중 6개(2.3%)뿐이었다.
   * 브랜드 SNS 운영은 우리 주력 라인 둘 중 하나인데 그 글이 안 나온다는 뜻이다.
   *
   * champion 은 기본값이기도 하므로 마지막에 두는 것이 맞다 — 좁은 신호부터
   * 걸러 내고, 남은 것을 본체가 받는다.
   */
  const order: LeadTargetKey[] = ["grant", "creator", "fandom", "champion"];
  for (const key of order) {
    const target = LEAD_TARGETS.find((x) => x.key === key)!;
    if (target.signals.test(t)) return target;
  }
  return LEAD_TARGETS[0];
}

export const leadTarget = (key: string): LeadTarget | null =>
  LEAD_TARGETS.find((t) => t.key === key) ?? null;

