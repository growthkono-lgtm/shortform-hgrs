export function readingTime(chars: number): number {
  // 한국어 기준 분당 약 500자로 잡는다. 소수점은 올림.
  return Math.max(1, Math.ceil(chars / 500));
}

export function pillar(key: PillarKey) {
  const found = PILLARS.find((p) => p.key === key);
  if (!found) throw new Error(`알 수 없는 필러: ${key}`);
  return found;
}

export function format(key: FormatKey) {
  const found = FORMATS.find((f) => f.key === key);
  if (!found) throw new Error(`알 수 없는 유형: ${key}`);
  return found;
}

/** 필러에 맞는 해그로시 어필 문단 원문 */
