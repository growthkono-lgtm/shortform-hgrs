export type AdFilmAudit = {
  ok: boolean;
  failures: string[];
  seconds: number;
};

/**
 * 납품 전 검사 — 통과 못 하면 안 나간다.
 *
 * 사람이 눈으로 보고 고르는 단계를 없애려면 기계가 셀 수 있는 기준이 있어야 한다.
 * 블로그의 `auditPost` 와 같은 역할이다.
 */
export function auditAdFilm(input: {
  seconds: number;
  cuts: number;
  hasProductShot: boolean;
  hasHeadline: boolean;
  hasCtaText: boolean;
  techniques: string[];
  narrationChars: number;
}): AdFilmAudit {
  const failures: string[] = [];

  if (input.seconds < 25 || input.seconds > 40) {
    failures.push(`길이 ${input.seconds}초 (기준 25~40초)`);
  }

  // 템포 — 포트폴리오 실측 평균 2.4초
  const avgCut = input.cuts > 0 ? input.seconds / input.cuts : Infinity;
  if (avgCut > TEMPO.maxCut) {
    failures.push(
      `컷 전환이 느립니다 — 평균 ${avgCut.toFixed(1)}초 (기준 ${TEMPO.maxCut}초 이내, 목표 ${TEMPO.targetCut}초). 브랜드 캠페인이 아니라 구매전환 소재입니다`,
    );
  }

  if (!input.hasProductShot) {
    failures.push("실물 제품컷이 없습니다 — AI 로 그린 제품은 납품하지 않습니다");
  }
  if (!input.hasHeadline) {
    failures.push("상단 고정 헤드라인이 없습니다 — 음소거로 보는 사람이 대다수입니다");
  }
  if (!input.hasCtaText) {
    failures.push("마지막에 행동 문구가 화면에 박혀 있지 않습니다");
  }

  // 광고 기법 — 제품을 모르는 사람에게 파는 소재라면 최소 넷은 있어야 한다
  const need = ["problem", "product", "howto", "solution"];
  const missing = need.filter((k) => !input.techniques.includes(k));
  if (missing.length) {
    const labels = missing.map(
      (k) => AD_TECHNIQUES.find((t) => t.key === k)?.label ?? k,
    );
    failures.push(`빠진 광고 기법: ${labels.join(" · ")}`);
  }

  /**
   * 나레이션 **밀도**. 2차는 `5자/초 초과면 실패` 였다 — 방향이 거꾸로였다.
   * 레퍼런스는 8.5자/초로 쉼 없이 말한다. 말이 적은 것이 문제지 많은 게
   * 문제가 아니다. 그래서 하한으로 뒤집는다.
   */
  const cps = input.seconds > 0 ? input.narrationChars / input.seconds : 0;
  if (cps < NARRATION.charsPerSecond.min) {
    failures.push(
      `나레이션이 성깁니다 — ${cps.toFixed(1)}자/초 (기준 ${NARRATION.charsPerSecond.min} 이상, 레퍼런스 ${NARRATION.charsPerSecond.target}). 빈 구간은 이탈 지점입니다`,
    );
  }

  return { ok: failures.length === 0, failures, seconds: input.seconds };
}
